class MyStack:

    def __init__(self):
        self.stack = deque()

    def push(self, x: int) -> None:
        self.stack.appendleft(x)

    def pop(self) -> int:
        i = self.stack.popleft()
        return i
    def top(self) -> int:
        i = self.stack[0]
        return i
    def empty(self) -> bool:
        return len(self.stack) == 0


